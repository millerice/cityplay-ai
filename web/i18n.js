const LangState = { lang: "en" };
function i18nLookup(key) {
  const table = I18N[LangState.lang] || I18N.en;
  return Object.prototype.hasOwnProperty.call(table, key) ? table[key] : (Object.prototype.hasOwnProperty.call(I18N.en, key) ? I18N.en[key] : null);
}
function t(key, params) {
  let value = i18nLookup(key);
  if (value === null) return key;
  if (params) for (const [name, replacement] of Object.entries(params)) value = value.split("{" + name + "}").join(String(replacement));
  return value;
}
function errorMessage(code, fallback) {
  const value = i18nLookup("err." + code);
  return value === null ? (fallback || t("err.GENERIC")) : value;
}
function categoryLabel(id) { return i18nLookup("cat." + id) || id; }
function excludeLabel(id) { return i18nLookup("xcat." + id) || id; }
function typeLabel(id) { return i18nLookup("type." + id) || id; }
function cityLabel(id) { return i18nLookup("city." + id) || id; }
function versionText(version, part, fallback) {
  // Prefer variant (e.g. adjacent_bridge); fall back to id for legacy payloads.
  const key = typeof version === "string" ? version : (version && (version.variant || version.id));
  const value = key ? i18nLookup("v." + key + "." + part) : null;
  return value === null ? (fallback || "") : value;
}
function applyElementText(element, value) {
  // Translate only the element's own text run; nested controls (label>select,
  // label>input, button>span) survive a language switch intact.
  const texts = Array.prototype.filter.call(element.childNodes, (n) => n.nodeType === 3 && n.nodeValue.trim());
  if (texts.length) {
    texts[0].nodeValue = value;
    for (let i = 1; i < texts.length; i++) element.removeChild(texts[i]);
  } else element.insertBefore(document.createTextNode(value), element.firstChild);
}
function setLang(lang) {
  if (lang !== "en" && lang !== "zh") return;
  LangState.lang = lang;
  try { localStorage.setItem("cityplay-lang", lang); } catch (_) { /* Private mode or storage blocked; the choice still applies for this page. */ }
  if (typeof document === "undefined" || !document.querySelectorAll) return;
  document.documentElement.setAttribute("lang", lang);
  document.querySelectorAll("[data-i18n]").forEach((element) => { const value = i18nLookup(element.getAttribute("data-i18n")); if (value !== null) applyElementText(element, value); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => { const value = i18nLookup(element.getAttribute("data-i18n-placeholder")); if (value !== null) element.placeholder = value; });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => { const value = i18nLookup(element.getAttribute("data-i18n-aria")); if (value !== null) element.setAttribute("aria-label", value); });
  const toggle = document.getElementById("lang-toggle");
  if (toggle) { toggle.textContent = lang === "en" ? "中文" : "EN"; toggle.setAttribute("aria-label", t("lang.switch")); }
  document.dispatchEvent(new Event("cityplay-lang-changed"));
}
if (typeof document !== "undefined" && document.querySelectorAll) {
  let stored = null;
  try { stored = localStorage.getItem("cityplay-lang"); } catch (_) { /* Storage unavailable; keep the English default. */ }
  setLang(stored === "zh" ? "zh" : "en");
  const toggle = document.getElementById("lang-toggle");
  if (toggle) toggle.addEventListener("click", () => setLang(LangState.lang === "en" ? "zh" : "en"));
}
